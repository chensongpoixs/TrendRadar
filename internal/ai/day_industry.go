func applyDayIndustryHTTPDefaults(c *AIClient) {
	if c == nil {
		return
	}
	cfg := config.Get()
	if c.timeout == 0 {
		tsec := cfg.AIAnalysis.EffectiveAIConfig(cfg.AI).Timeout
		if tsec <= 0 {
			tsec = 180
		}
		c.timeout = time.Duration(tsec) * time.Second
		c.client.Timeout = c.timeout
	}
	if c.numRetries > 1 {
		c.numRetries = 1
	}
}
